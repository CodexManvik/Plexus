# ── Tables the ORM owns — all must exist for the schema to be considered valid ─

_EXPECTED_TABLES: frozenset[str] = frozenset({
    "contracts_master",
    "contract_parameters_extracted",
    "contract_document_chunks",
    "contract_audit_trail",
    "master_extraction_rules",
    "metadata_options",
})

# VECTOR column dimension requirements. If any actual dim doesn't match the
# configured EMBEDDING_VECTOR_DIM, the whole schema is rebuilt.
_VECTOR_COLUMN_DIMS: dict[str, dict[str, int]] = {
    "contracts_master": {
        "document_vector": settings.embedding_vector_dim,
    },
    "contract_parameters_extracted": {
        "vector_embed": settings.embedding_vector_dim,
    },
    "contract_document_chunks": {
        "chunk_vector": settings.embedding_vector_dim,
    },
}

# Identity columns — their absence means the schema was created without Oracle
# GENERATED BY DEFAULT AS IDENTITY (e.g., an old SQLite migration).
_IDENTITY_COLUMNS: dict[str, set[str]] = {
    "contract_parameters_extracted": {"parameter_id"},
    "contract_audit_trail": {"audit_id"},
    "master_extraction_rules": {"rule_id"},
    "metadata_options": {"option_id"},
    "contract_document_chunks": {"chunk_id"},
}

# Oracle VECTOR index DDL — each wrapped in anonymous PL/SQL so the block
# silently ignores ORA-00955 (object already exists) on restart.
# INMEMORY NEIGHBOR GRAPH is the Oracle 23ai HNSW index type (zero training
# data requirement, suitable for small-to-medium datasets).
_VECTOR_INDEX_DDL: list[tuple[str, str]] = [
    (
        "idx_chunk_vector",
        """
        CREATE VECTOR INDEX idx_chunk_vector
        ON contract_document_chunks(chunk_vector)
        ORGANIZATION INMEMORY NEIGHBOR GRAPH
        DISTANCE COSINE
        WITH TARGET ACCURACY 95
        """,
    ),
    (
        "idx_param_vector",
        """
        CREATE VECTOR INDEX idx_param_vector
        ON contract_parameters_extracted(vector_embed)
        ORGANIZATION INMEMORY NEIGHBOR GRAPH
        DISTANCE COSINE
        WITH TARGET ACCURACY 95
        """,
    ),
    (
        "idx_doc_vector",
        """
        CREATE VECTOR INDEX idx_doc_vector
        ON contracts_master(document_vector)
        ORGANIZATION INMEMORY NEIGHBOR GRAPH
        DISTANCE COSINE
        WITH TARGET ACCURACY 95
        """,
    ),
]


# ── Synchronous schema inspection & drop logic (runs inside run_sync) ─────────

def _ensure_schema(sync_conn) -> None:
    """
    Inspects the live Oracle schema and drops all ORM-owned tables if ANY of the
    following conditions are true:

      1. A table from _EXPECTED_TABLES is missing entirely.
      2. A VECTOR column has the wrong number of dimensions (EMBEDDING_VECTOR_DIM mismatch).
      3. An Identity column is missing (schema created by a non-Oracle migration).

    After this function returns, the caller must invoke Base.metadata.create_all
    to recreate all tables from ORM definitions. For non-Oracle dialects (e.g.,
    SQLite in dev), this function is a no-op — SQLAlchemy handles those natively.
    """
    if sync_conn.dialect.name != "oracle":
        return

    inspector = inspect(sync_conn)
    existing_tables: set[str] = set(inspector.get_table_names())

    # ── Check 1: missing tables ───────────────────────────────────────────────
    missing = _EXPECTED_TABLES - existing_tables
    if missing:
        print(
            f"[Schema] Missing tables detected: {sorted(missing)}. "
            "Dropping all and recreating from ORM metadata.",
            file=sys.stderr,
        )
        Base.metadata.drop_all(sync_conn)
        return  # create_all will run immediately after

    # ── Check 2: VECTOR dimension mismatch ───────────────────────────────────
    for table_name, columns in _VECTOR_COLUMN_DIMS.items():
        if table_name not in existing_tables:
            continue
        col_map = {
            col["name"].lower(): col
            for col in inspector.get_columns(table_name)
        }
        for col_name, expected_dim in columns.items():
            col_info = col_map.get(col_name)
            if col_info is None:
                continue
            actual_dim = getattr(col_info.get("type"), "dim", None)
            if actual_dim is not None and actual_dim != expected_dim:
                print(
                    f"[Schema] VECTOR dim mismatch on {table_name}.{col_name}: "
                    f"expected={expected_dim}, actual={actual_dim}. Rebuilding.",
                    file=sys.stderr,
                )
                Base.metadata.drop_all(sync_conn)
                return

    # ── Check 3: missing Identity columns ────────────────────────────────────
    for table_name, identity_cols in _IDENTITY_COLUMNS.items():
        if table_name not in existing_tables:
            continue
        col_map = {
            col["name"].lower(): col
            for col in inspector.get_columns(table_name)
        }
        for col_name in identity_cols:
            col_info = col_map.get(col_name)
            if col_info is not None and col_info.get("identity") is None:
                print(
                    f"[Schema] Identity missing on {table_name}.{col_name}. Rebuilding.",
                    file=sys.stderr,
                )
                Base.metadata.drop_all(sync_conn)
                return

    print("[Schema] All tables present and schema valid — no rebuild required.", file=sys.stderr)


# ── Oracle VECTOR index creation (async, idempotent via PL/SQL exception block)

async def _ensure_vector_indexes(conn) -> None:
    """
    Creates Oracle 23ai VECTOR indexes if they do not already exist.
    Each DDL statement is wrapped in an anonymous PL/SQL block that silently
    swallows ORA-00955 (name already used by an existing object), making this
    safe to call on every restart.

    Skipped entirely for non-Oracle dialects.
    """
    if engine.dialect.name != "oracle":
        return

    for index_name, ddl in _VECTOR_INDEX_DDL:
        plsql = f"""
        BEGIN
            EXECUTE IMMEDIATE q'[{ddl.strip()}]';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE = -955 THEN NULL;  -- ORA-00955: name already used
                ELSE RAISE;
                END IF;
        END;
        """
        try:
            await conn.execute(text(plsql))
            print(f"[Schema] VECTOR index '{index_name}' ensured.", file=sys.stderr)
        except Exception as exc:
            # Non-fatal: VECTOR indexes improve performance but queries fall back
            # to full table scans without them. Log and continue.
            print(
                f"[Schema] WARNING: Could not create VECTOR index '{index_name}': {exc}. "
                "Queries will use full scans. This is expected on non-23ai Oracle instances.",
                file=sys.stderr,
            )


# ── FastAPI lifespan ───────────────────────────────────────────────────────────

@asynccontextmanager
async def lifespan(_: FastAPI):
    """
    Startup sequence (runs once per server process start):

      1. _ensure_schema   — drop stale/partial schema if needed (sync, inside run_sync).
      2. create_all       — create any missing ORM-mapped tables (idempotent).
      3. _ensure_vector_indexes — create VECTOR ANN indexes (idempotent PL/SQL).
      4. seed_defaults    — insert seed rules and metadata options (upsert-safe).

    Shutdown:
      5. Close the LLM HTTP client pool.
    """
    print("[Startup] Beginning schema bootstrap...", file=sys.stderr)

    try:
        async with engine.begin() as conn:
            # Step 1 + 2: inspect, optionally drop, then create all ORM tables.
            await conn.run_sync(_ensure_schema)
            await conn.run_sync(Base.metadata.create_all)
            print("[Startup] ORM tables created/verified.", file=sys.stderr)

            # Step 3: VECTOR indexes (Oracle 23ai only, idempotent).
            await _ensure_vector_indexes(conn)

        # Step 4: Seed default rules and metadata (runs in its own session).
        async with AsyncSessionLocal() as session:
            await seed_defaults(session)
            print("[Startup] Seed data applied.", file=sys.stderr)

        print("[Startup] Schema bootstrap complete. Server ready.", file=sys.stderr)

        yield

    finally:
        await azure_llm.aclose()
        print("[Shutdown] LLM client closed.", file=sys.stderr)


